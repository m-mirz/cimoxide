/// A set of combustion turbines and steam turbines where the exhaust heat from the combustion turbines is recovered to make steam for the steam turbines, resulting in greater overall plant efficiency.
#[derive(Debug, Default, Clone, serde::Serialize, serde::Deserialize)]
pub struct CombinedCyclePlant {
    #[serde(flatten)]
    pub base: super::PowerSystemResource,
}
impl crate::base::CimElement for CombinedCyclePlant {
    fn mrid(&self) -> &str { &self.base.base.id }
    fn type_name(&self) -> &'static str { "CombinedCyclePlant" }
    fn as_any(&self) -> &dyn std::any::Any { self }
    fn to_json_value(&self) -> serde_json::Value {
        serde_json::to_value(self).unwrap_or(serde_json::Value::Null)
    }
    fn to_block(&self) -> crate::base::RdfBlock {
        let mut block = self.base.to_block();
        block.type_name = "CombinedCyclePlant".to_string();
        block
    }
}

