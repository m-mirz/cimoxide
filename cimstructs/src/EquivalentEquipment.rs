impl crate::base::CimElement for EquivalentEquipment {
    fn mrid(&self) -> &str { &self.base.base.base.base.id }
    fn type_name(&self) -> &'static str { "EquivalentEquipment" }
    fn as_any(&self) -> &dyn std::any::Any { self }
    fn to_json_value(&self) -> serde_json::Value {
        serde_json::to_value(self).unwrap_or(serde_json::Value::Null)
    }
    fn to_block(&self) -> crate::base::RdfBlock {
        let mut block = self.base.to_block();
        block.type_name = "EquivalentEquipment".to_string();
        if let Some(ref v) = self.equivalent_network {
            block.fields.insert("EquivalentEquipment.EquivalentNetwork".into(), crate::base::FieldValue::Resource(v.mrid.clone()));
        }
        block
    }
}

