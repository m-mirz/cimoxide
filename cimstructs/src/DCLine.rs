/// Overhead lines and/or cables connecting two or more HVDC substations.
#[derive(Debug, Default, Clone, serde::Serialize, serde::Deserialize)]
pub struct DCLine {
    #[serde(flatten)]
    pub base: super::DCEquipmentContainer,
    /// The SubGeographicalRegion containing the DC line.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub region: Option<super::base::MridRef>,
}
impl crate::base::CimElement for DCLine {
    fn mrid(&self) -> &str { &self.base.base.base.base.base.id }
    fn type_name(&self) -> &'static str { "DCLine" }
    fn as_any(&self) -> &dyn std::any::Any { self }
    fn to_json_value(&self) -> serde_json::Value {
        serde_json::to_value(self).unwrap_or(serde_json::Value::Null)
    }
    fn to_block(&self) -> crate::base::RdfBlock {
        let mut block = self.base.to_block();
        block.type_name = "DCLine".to_string();
        if let Some(ref v) = self.region {
            block.fields.insert("DCLine.Region".into(), crate::base::FieldValue::Resource(v.mrid.clone()));
        }
        block
    }
}

