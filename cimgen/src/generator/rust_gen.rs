//! Emits the model crate's generated module: a class table per family, the
//! CGMES version constants and the profile-membership tables.
//!
//! Every family is a table of classes decoded into property bags; there are no
//! generated types. What a class declares lives in its rows.

use std::collections::BTreeMap;
use std::fmt::Write as FmtWrite;
use std::fs;
use std::path::Path;

use crate::schema::model::*;

/// Write the generated module for `spec` (CGMES) and the other families.
pub fn generate_rust(
    spec: &mut CimSpecification,
    others: &[&CimSpecification],
    output_dir: &Path,
) -> Result<(), Box<dyn std::error::Error>> {
    fs::create_dir_all(output_dir)?;
    set_lang_types(spec);
    let spec: &CimSpecification = &*spec;

    fs::write(output_dir.join("constants.rs"), render_constants(spec))?;
    fs::write(output_dir.join("profile_meta.rs"), render_profile_meta(spec))?;

    let families: Vec<&CimSpecification> = std::iter::once(spec).chain(others.iter().copied()).collect();
    for f in &families {
        let file = output_dir.join(format!("{}_classes.rs", f.family.id));
        fs::write(file, super::classes_gen::render_classes(f))?;
    }
    let ids: Vec<&str> = families.iter().map(|f| f.family.id).collect();
    fs::write(output_dir.join("mod.rs"), render_mod(&ids))?;
    Ok(())
}

/// The `generated` module of the model crate, re-exported by its hand-written
/// `lib.rs`.
fn render_mod(family_ids: &[&str]) -> String {
    let mut s = String::new();
    writeln!(s, "// Generated by cimgen — do not edit by hand.").unwrap();
    writeln!(s).unwrap();
    writeln!(s, "pub mod constants;").unwrap();
    writeln!(s, "pub mod profile_meta;").unwrap();
    for id in family_ids {
        writeln!(s, "pub mod {id}_classes;").unwrap();
    }
    s
}

// --- type mapping -----------------------------------------------------------

fn map_lang_type(data_type: &str) -> &'static str {
    match data_type {
        DATA_TYPE_STRING | DATA_TYPE_DATE | DATA_TYPE_DATE_TIME | DATA_TYPE_MONTH_DAY | "URI" => {
            "String"
        }
        DATA_TYPE_BOOLEAN => "bool",
        DATA_TYPE_INTEGER => "i64",
        DATA_TYPE_FLOAT | DATA_TYPE_DECIMAL => "f64",
        _ => "String",
    }
}

fn set_lang_types(spec: &mut CimSpecification) {
    for dt in spec.cim_datatypes.values_mut() {
        dt.lang_type = map_lang_type(&dt.primitive_type).to_string();
    }
    for p in spec.primitive_types.values_mut() {
        p.lang_type = map_lang_type(&p.data_type).to_string();
    }
    for t in spec.types.values_mut() {
        for attr in &mut t.attributes {
            let base = map_lang_type(&attr.data_type);
            attr.lang_type = if attr.is_list && (attr.is_primitive || attr.is_cim_datatype) {
                format!("Vec<{base}>")
            } else {
                base.to_string()
            };
        }
    }
}

fn render_constants(spec: &CimSpecification) -> String {
    let mut s = String::new();
    writeln!(s, "pub const CIM_VERSION: &str = \"{}\";", spec.cgmes_version).unwrap();
    writeln!(s).unwrap();
    writeln!(
        s,
        "pub static CIM_NAMESPACES: &[(&str, &str)] = &["
    )
    .unwrap();
    let mut pairs: Vec<(&String, &String)> = spec.profile_namespaces.iter().collect();
    pairs.sort_by_key(|(k, _)| k.as_str());
    for (k, v) in pairs {
        writeln!(s, "    (\"{k}\", \"{v}\"),").unwrap();
    }
    writeln!(s, "];").unwrap();
    s
}

fn render_profile_meta(spec: &CimSpecification) -> String {
    let mut s = String::new();
    writeln!(s, "// Generated by cimgen — do not edit by hand.").unwrap();
    writeln!(s).unwrap();

    // TYPE_ORIGINS: sorted by type name
    writeln!(
        s,
        "/// `(type_name, origins)` — `origins[0]` is the primary (dominant) profile."
    )
    .unwrap();
    writeln!(
        s,
        "pub static TYPE_ORIGINS: &[(&str, &[&str])] = &["
    )
    .unwrap();
    let mut type_ids: Vec<&String> = spec.types.keys().collect();
    type_ids.sort();
    for id in type_ids {
        let t = &spec.types[id];
        if t.origins.is_empty() {
            continue;
        }
        let origins: Vec<String> = t.origins.iter().map(|o| format!("\"{o}\"")).collect();
        writeln!(s, "    (\"{id}\", &[{}]),", origins.join(", ")).unwrap();
    }
    writeln!(s, "];").unwrap();
    writeln!(s).unwrap();

    // ATTR_ORIGINS: collect all (attr_id → origins) from all types, dedup via BTreeMap
    // Same attr_id can appear in multiple type attribute lists (inherited attrs) — merge origins.
    let mut attr_map: BTreeMap<String, Vec<String>> = BTreeMap::new();
    let mut type_ids2: Vec<&String> = spec.types.keys().collect();
    type_ids2.sort();
    for id in type_ids2 {
        let t = &spec.types[id];
        for attr in t.attributes.iter().filter(|a| a.is_association_used) {
            if attr.origins.is_empty() {
                continue;
            }
            let entry = attr_map.entry(attr.id.clone()).or_default();
            for o in &attr.origins {
                if !entry.contains(o) {
                    entry.push(o.clone());
                }
            }
        }
    }
    writeln!(
        s,
        "/// `(attr_id, origins)` — `origins[0]` is the primary (dominant) profile."
    )
    .unwrap();
    writeln!(
        s,
        "/// `attr_id` matches the field key in `Element::fields`."
    )
    .unwrap();
    writeln!(
        s,
        "pub static ATTR_ORIGINS: &[(&str, &[&str])] = &["
    )
    .unwrap();
    for (attr_id, mut origins) in attr_map {
        // Sort origins consistently: EQ first (priority 1), rest alphabetically
        origins.sort_by(|a, b| {
            let pa = if a == "EQ" { 0u32 } else { 1 };
            let pb = if b == "EQ" { 0u32 } else { 1 };
            pa.cmp(&pb).then(a.cmp(b))
        });
        let quoted: Vec<String> = origins.iter().map(|o| format!("\"{o}\"")).collect();
        writeln!(s, "    (\"{attr_id}\", &[{}]),", quoted.join(", ")).unwrap();
    }
    writeln!(s, "];").unwrap();
    writeln!(s).unwrap();

    // PROFILE_URIS: (keyword, owl_version_iri) for each known profile ontology
    writeln!(
        s,
        "/// `(profile_code, profile_uri)` — versioned URI for `md:Model.profile`."
    )
    .unwrap();
    writeln!(
        s,
        "pub static PROFILE_URIS: &[(&str, &str)] = &["
    )
    .unwrap();
    let mut ontologies: Vec<(&String, &CimOntology)> = spec.ontologies.iter().collect();
    ontologies.sort_by_key(|(k, _)| k.as_str());
    for (keyword, ont) in ontologies {
        if ont.owl_version_iri.is_empty() {
            continue;
        }
        writeln!(s, "    (\"{keyword}\", \"{}\"),", ont.owl_version_iri).unwrap();
    }
    writeln!(s, "];").unwrap();
    writeln!(s).unwrap();

    // TYPE_NS: RDF namespace IRI per CIM class. The decoder drops the XML prefix
    // (`local_name()`), so this is the only way back to a class IRI at runtime.
    writeln!(
        s,
        "/// `(type_name, namespace)` — RDF namespace IRI of each CIM class, trailing `#` included."
    )
    .unwrap();
    writeln!(s, "pub static TYPE_NS: &[(&str, &str)] = &[").unwrap();
    let mut ns_type_ids: Vec<&String> = spec.types.keys().collect();
    ns_type_ids.sort();
    for id in ns_type_ids {
        let t = &spec.types[id];
        if t.namespace.is_empty() {
            continue;
        }
        writeln!(s, "    (\"{id}\", \"{}\"),", t.namespace).unwrap();
    }
    writeln!(s, "];").unwrap();
    writeln!(s).unwrap();

    // ATTR_RDF: (attr_id, namespace, range, kind) for every attribute of every type.
    // Deduped by attr_id like ATTR_ORIGINS above — the same id recurs across inheriting
    // types. Unlike ATTR_ORIGINS this is *not* filtered on `is_association_used`:
    // an element's fields can hold keys outside the profiles' used associations, and a
    // predicate IRI is wanted for those too.
    let mut rdf_map: BTreeMap<String, (String, String, u8)> = BTreeMap::new();
    let mut type_ids3: Vec<&String> = spec.types.keys().collect();
    type_ids3.sort();
    for id in type_ids3 {
        for attr in &spec.types[id].attributes {
            if attr.namespace.is_empty() || rdf_map.contains_key(&attr.id) {
                continue;
            }
            // Test the enum registry directly rather than trusting `is_enum_value`:
            // `eu:OperationalLimitType.kind` ranges over the `eu:LimitKind` enumeration but
            // is classified as a plain class reference upstream, so it would otherwise get an
            // MRID-shaped object IRI instead of the enum value IRI.
            let (range, kind) = if let Some(e) = spec.enums.get(&attr.rdf_range) {
                // The decoder strips the fragment off enum values, so the enum's own
                // namespace is what rebuilds `<ns>WindingConnection.D` from `WindingConnection.D`.
                (e.namespace.clone(), 2u8)
            } else if attr.is_enum_value || attr.is_primitive || attr.is_cim_datatype {
                (xsd_iri(attr), 0u8)
            } else {
                (String::new(), 1u8)
            };
            rdf_map.insert(attr.id.clone(), (attr.namespace.clone(), range, kind));
        }
    }
    writeln!(
        s,
        "/// `(attr_id, namespace, range, kind)` — `attr_id` matches the key in `Element::fields`."
    )
    .unwrap();
    writeln!(
        s,
        "/// `kind`: 0 = literal, 1 = association (IRI), 2 = enum value (IRI)."
    )
    .unwrap();
    writeln!(
        s,
        "/// `range`: for kind 0 the XSD datatype IRI, for kind 2 the enum's namespace IRI,"
    )
    .unwrap();
    writeln!(s, "/// empty for kind 1.").unwrap();
    writeln!(s, "pub static ATTR_RDF: &[(&str, &str, &str, u8)] = &[").unwrap();
    for (attr_id, (ns, range, kind)) in rdf_map {
        writeln!(s, "    (\"{attr_id}\", \"{ns}\", \"{range}\", {kind}),").unwrap();
    }
    writeln!(s, "];").unwrap();
    s
}

/// XSD datatype IRI for a literal-valued attribute, falling back on the generated Rust
/// type when the CIM datatype is unset.
///
/// CGMES `Float` maps to `xsd:double`, not `xsd:float`: the decoder parses into `f64`, and
/// claiming single precision would make `FILTER(?r > 0.1)` disagree with the value that was
/// actually decoded.
fn xsd_iri(attr: &CimAttribute) -> String {
    const XSD: &str = "http://www.w3.org/2001/XMLSchema#";
    let name = match attr.data_type.as_str() {
        DATA_TYPE_STRING => "string",
        DATA_TYPE_INTEGER => "integer",
        DATA_TYPE_BOOLEAN => "boolean",
        DATA_TYPE_FLOAT => "double",
        DATA_TYPE_DECIMAL => "decimal",
        DATA_TYPE_DATE => "date",
        DATA_TYPE_DATE_TIME => "dateTime",
        DATA_TYPE_MONTH_DAY => "gMonthDay",
        // `md:Model.profile` and friends declare `eu:URI`, and the SHACL files type their
        // values `^^xsd:anyURI`.
        "URI" => "anyURI",
        // List-valued literals carry a `Vec<..>` lang type; the element type is what matters.
        _ => match attr
            .lang_type
            .trim_start_matches("Vec<")
            .trim_end_matches('>')
        {
            "f64" => "double",
            "i64" => "integer",
            "bool" => "boolean",
            "String" => "string",
            _ => return String::new(),
        },
    };
    format!("{XSD}{name}")
}
